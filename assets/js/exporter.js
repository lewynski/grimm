/**
 * Produces the two save formats: a self-contained HTML file and a PDF via
 * the browser's print dialog with a chosen column layout.
 *
 * save(paper)               → triggers download of grimm-<title>.html
 * downloadPDF(paper, cols)  → applies column CSS then calls window.print()
 */
(function (root) {
  'use strict';

  function slug(title) {
    return String(title || 'notes')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 48) || 'notes';
  }

  function download(blob, name) {
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = name;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 2000);
  }

  /** Grabs the full text of the first stylesheet on the page. */
  async function getCSS() {
    var links = Array.prototype.slice.call(document.querySelectorAll('link[rel="stylesheet"]'));
    for (var i = 0; i < links.length; i += 1) {
      try {
        var res = await fetch(links[i].href);
        if (res.ok) {
          var css = await res.text();
          // Ensure the offline copy also suppresses browser print headers/footers
          if (css.indexOf('@page') < 0) {
            css = '@page { margin: 0; }\n' + css;
          }
          return css;
        }
      } catch (err) { /* skip */ }
    }
    return '@page { margin: 0; }';
  }

  /** Grabs the source text of a <script src="..."> tag. */
  async function getScript(src) {
    try {
      var res = await fetch(src);
      return res.ok ? await res.text() : '';
    } catch (err) {
      return '';
    }
  }

  /**
   * Builds a self-contained HTML document that boots the notes viewer with
   * the paper JSON embedded, using no external resources.
   */
  async function buildHtml(paper) {
    var css = await getCSS();

    // Gather the two client-side scripts needed by the offline file
    var scripts = await Promise.all([
      getScript('assets/js/notes.js'),
    ]);

    var safeJson = JSON.stringify(paper).replace(/<\/script/gi, '<\\/script');

    var doc = [
      '<!doctype html>',
      '<html lang="en" data-theme="dark">',
      '<head>',
      '<meta charset="utf-8" />',
      '<meta name="viewport" content="width=device-width, initial-scale=1" />',
      '<title>' + esc(paper.title || 'Grimm Notes') + '</title>',
      '<style>' + css + '</style>',
      '<script>',
      '/* Theme: honour a saved light choice before first paint */',
      'try { var _t = localStorage.getItem("gr-theme");',
      'document.documentElement.setAttribute("data-theme", _t === "light" ? "light" : "dark"); } catch(e){}',
      '<\/script>',
      '</head>',
      '<body class="offline">',
      '<header class="masthead">',
      '  <div class="masthead-in">',
      '    <span class="wordmark">Grimm</span>',
      '    <span class="masthead-right">',
      '      <span class="masthead-meta">' + esc(paper.title || '') + ' \u00b7 ' + esc(paper.made || '') + '</span>',
      '      <button class="btn btn-small btn-quiet no-print" id="pdf-btn" type="button">Download PDF</button>',
      '      <button class="theme no-print" id="theme" type="button">&#9789;</button>',
      '    </span>',
      '  </div>',
      '</header>',
      '<main class="shell" id="notes-root"></main>',
      '<footer class="footer shell no-print">',
      '  <p>Generated by Grimm. For study use only.</p>',
      '</footer>',
      '',
      '<!-- Column picker overlay -->',
      '<div class="export-dialog hidden" id="col-picker" role="dialog" aria-modal="true" aria-label="Download PDF">',
      '  <div class="export-card">',
      '    <h2>Download PDF</h2>',
      '    <p class="export-note">Choose a column layout for printing.</p>',
      '    <fieldset class="pdf-layout">',
      '      <legend>Layout</legend>',
      '      <label><input type="radio" name="col" value="1" checked /> Single column</label>',
      '      <label><input type="radio" name="col" value="2" /> 2 columns</label>',
      '      <label><input type="radio" name="col" value="3" /> 3 columns</label>',
      '    </fieldset>',
      '    <div class="export-actions">',
      '      <button class="btn btn-quiet" id="col-cancel" type="button">Cancel</button>',
      '      <button class="btn" id="col-print" type="button">Print / Save PDF</button>',
      '    </div>',
      '  </div>',
      '</div>',
      '',
      '<script>',
      scripts[0],
      '<\/script>',
      '<script>',
      '(function(){',
      '  var paper = ' + safeJson + ';',
      '  var root = document.getElementById("notes-root");',
      '  GR.notes.mount(root, paper, { mode: paper.mode || "chronological" });',
      '',
      '  /* Theme toggle */',
      '  var THEME_KEY = "gr-theme";',
      '  var themeBtn = document.getElementById("theme");',
      '  function themeNow(){ return document.documentElement.getAttribute("data-theme") === "light" ? "light" : "dark"; }',
      '  function paintTheme(){ themeBtn.textContent = themeNow() === "dark" ? "\\u263d" : "\\u2600"; }',
      '  themeBtn.addEventListener("click", function(){',
      '    var next = themeNow() === "dark" ? "light" : "dark";',
      '    document.documentElement.setAttribute("data-theme", next);',
      '    try{ localStorage.setItem(THEME_KEY, next); }catch(e){}',
      '    paintTheme();',
      '  });',
      '  paintTheme();',
      '',
      '  /* PDF button */',
      '  var picker = document.getElementById("col-picker");',
      '  var pdfBtn = document.getElementById("pdf-btn");',
      '  var cancelBtn = document.getElementById("col-cancel");',
      '  var printBtn = document.getElementById("col-print");',
      '  pdfBtn.addEventListener("click", function(){ picker.classList.remove("hidden"); });',
      '  cancelBtn.addEventListener("click", function(){ picker.classList.add("hidden"); });',
      '  picker.addEventListener("click", function(e){ if(e.target===picker) picker.classList.add("hidden"); });',
      '  printBtn.addEventListener("click", function(){',
      '    picker.classList.add("hidden");',
      '    var chosen = document.querySelector("input[name=col]:checked");',
      '    var cols = chosen ? Number(chosen.value) : 1;',
      '    document.documentElement.style.setProperty("--print-cols", String(cols));',
      '    window.print();',
      '  });',
      '})();',
      '<\/script>',
      '</body>',
      '</html>',
    ].join('\n');

    return doc;
  }

  function esc(str) {
    return String(str == null ? '' : str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  /** Saves the offline HTML file. */
  async function save(paper) {
    var html = await buildHtml(paper);
    var name = 'grimm-' + slug(paper.title) + '.html';
    var blob = new Blob([html], { type: 'text/html; charset=utf-8' });
    download(blob, name);
    return { name: name, size: blob.size };
  }

  /**
   * Applies column CSS and opens the print dialog.
   * columns: 1 | 2 | 3
   */
  function downloadPDF(paper, columns) {
    var cols = [1, 2, 3].indexOf(Number(columns)) >= 0 ? Number(columns) : 1;
    document.documentElement.style.setProperty('--print-cols', String(cols));
    var name = 'grimm-' + slug(paper.title) + '.pdf';
    window.print();
    return { name: name };
  }

  root.GR = root.GR || {};
  root.GR.exporter = { save: save, downloadPDF: downloadPDF };
})(typeof window !== 'undefined' ? window : globalThis);
