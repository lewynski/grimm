/**
 * Produces the two save formats: a self-contained HTML file and a real PDF
 * download generated with jsPDF (no print dialog, no html2canvas).
 *
 * save(paper)               → triggers download of grimm-<title>.html
 * downloadPDF(paper, cols)  → generates a PDF with jsPDF and downloads it
 */
(function (root) {
  'use strict';

  function slug(title) {
    return String(title || 'notes')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 48) || 'notes';
  }

  function downloadBlob(blob, name) {
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = name;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 2000);
  }

  /** Grabs the full text of the first stylesheet on the page. */
  async function getCSS() {
    var links = Array.prototype.slice.call(document.querySelectorAll('link[rel="stylesheet"]'));
    for (var i = 0; i < links.length; i += 1) {
      try {
        var res = await fetch(links[i].href);
        if (res.ok) {
          var css = await res.text();
          if (css.indexOf('@page') < 0) {
            css = '@page { margin: 0; }\n' + css;
          }
          return css;
        }
      } catch (err) { /* skip */ }
    }
    return '@page { margin: 0; }';
  }

  async function getScript(src) {
    try {
      var res = await fetch(src);
      return res.ok ? await res.text() : '';
    } catch (err) {
      return '';
    }
  }

  function esc(str) {
    return String(str == null ? '' : str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  /* ── HTML export (unchanged) ────────────────────────────────────────────── */

  async function buildHtml(paper) {
    var css = await getCSS();
    var scripts = await Promise.all([getScript('assets/js/notes.js')]);
    var safeJson = JSON.stringify(paper).replace(/<\/script/gi, '<\\/script');

    var doc = [
      '<!doctype html>',
      '<html lang="en" data-theme="dark">',
      '<head>',
      '<meta charset="utf-8" />',
      '<meta name="viewport" content="width=device-width, initial-scale=1" />',
      '<title>' + esc(paper.title || 'Grimm Notes') + '</title>',
      '<style>' + css + '</style>',
      '<script>',
      'try { var _t = localStorage.getItem("gr-theme");',
      'document.documentElement.setAttribute("data-theme", _t === "light" ? "light" : "dark"); } catch(e){}',
      '<\/script>',
      '</head>',
      '<body class="offline">',
      '<header class="masthead">',
      '  <div class="masthead-in">',
      '    <span class="wordmark">Grimm</span>',
      '    <span class="masthead-right">',
      '      <span class="masthead-meta">' + esc(paper.title || '') + ' \u00b7 ' + esc(paper.made || '') + '</span>',
      '      <button class="theme no-print" id="theme" type="button">&#9789;</button>',
      '    </span>',
      '  </div>',
      '</header>',
      '<main class="shell" id="notes-root"></main>',
      '<footer class="footer shell no-print">',
      '  <p>Generated by Grimm. For study use only.</p>',
      '</footer>',
      '<script>',
      scripts[0],
      '<\/script>',
      '<script>',
      '(function(){',
      '  var paper = ' + safeJson + ';',
      '  var root = document.getElementById("notes-root");',
      '  GR.notes.mount(root, paper, { mode: paper.mode || "chronological" });',
      '  var THEME_KEY = "gr-theme";',
      '  var themeBtn = document.getElementById("theme");',
      '  function themeNow(){ return document.documentElement.getAttribute("data-theme") === "light" ? "light" : "dark"; }',
      '  function paintTheme(){ themeBtn.textContent = themeNow() === "dark" ? "\\u263d" : "\\u2600"; }',
      '  themeBtn.addEventListener("click", function(){',
      '    var next = themeNow() === "dark" ? "light" : "dark";',
      '    document.documentElement.setAttribute("data-theme", next);',
      '    try{ localStorage.setItem(THEME_KEY, next); }catch(e){}',
      '    paintTheme();',
      '  });',
      '  paintTheme();',
      '})();',
      '<\/script>',
      '</body>',
      '</html>',
    ].join('\n');
    return doc;
  }

  async function save(paper) {
    var html = await buildHtml(paper);
    var name = 'grimm-' + slug(paper.title) + '.html';
    var blob = new Blob([html], { type: 'text/html; charset=utf-8' });
    downloadBlob(blob, name);
    return { name: name, size: blob.size };
  }

  /* ── PDF generation with jsPDF ──────────────────────────────────────────── */

  var jspdfLib = null;

  function loadJsPdf() {
    if (jspdfLib) return Promise.resolve(jspdfLib);
    return new Promise(function (resolve, reject) {
      var script = document.createElement('script');
      script.src = 'https://cdn.jsdelivr.net/npm/jspdf@2.5.2/dist/jspdf.umd.min.js';
      script.onload = function () {
        jspdfLib = root.jspdf;
        resolve(jspdfLib);
      };
      script.onerror = function () {
        reject(new Error('Could not load the PDF library. Check your internet connection.'));
      };
      document.head.appendChild(script);
    });
  }

  /**
   * Generates a real PDF and triggers download. No print dialog.
   * columns: 1 | 2 | 3
   */
  async function downloadPDF(paper, columns) {
    var cols = [1, 2, 3].indexOf(Number(columns)) >= 0 ? Number(columns) : 1;
    var name = 'grimm-' + slug(paper.title) + '.pdf';

    var lib = await loadJsPdf();
    var doc = new lib.jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' });

    var pw = doc.internal.pageSize.getWidth();   // 210
    var ph = doc.internal.pageSize.getHeight();   // 297

    var marginL = 14;
    var marginR = 14;
    var marginT = 16;
    var marginB = 14;
    var usableW = pw - marginL - marginR;       // ~182
    var gutter = 8;

    // Column geometry
    var colW = (usableW - gutter * (cols - 1)) / cols;
    var colX = [];
    for (var c = 0; c < cols; c++) {
      colX.push(marginL + c * (colW + gutter));
    }

    // Resolve note order
    var notes = paper.notes || [];
    var ordered = notes;
    if (paper.mode === 'randomised' && paper.order && paper.order.length === notes.length) {
      ordered = paper.order.map(function (i) { return notes[i]; });
    }

    // State
    var curCol = 0;
    var y = marginT;

    function newPage() {
      doc.addPage();
      y = marginT;
      curCol = 0;
    }

    function nextCol() {
      curCol++;
      if (curCol >= cols) {
        newPage();
      } else {
        y = marginT;
      }
    }

    function checkSpace(needed) {
      if (y + needed > ph - marginB) {
        if (cols > 1 && curCol < cols - 1) {
          nextCol();
        } else {
          newPage();
        }
      }
    }

    // ── Title ──
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(20);
    var titleLines = doc.splitTextToSize(paper.title || 'Notes', usableW);
    doc.text(titleLines, marginL, y + 6);
    y += titleLines.length * 8 + 4;

    // ── Meta line ──
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(100, 100, 100);
    var metaText = ordered.length + (ordered.length === 1 ? ' slide' : ' slides') +
      '  \u00b7  ' + (paper.mode === 'randomised' ? 'Randomised order' : 'Chronological order') +
      '  \u00b7  ' + (paper.made || '');
    doc.text(metaText, marginL, y);
    y += 4;

    // Source files
    var sourceFiles = (paper.files || []).map(function (f) { return f.name; }).join(', ');
    if (sourceFiles) {
      doc.setFontSize(8);
      doc.setTextColor(120, 120, 120);
      doc.text('Source: ' + sourceFiles, marginL, y);
      y += 4;
    }

    // ── Horizontal rule ──
    doc.setDrawColor(170, 170, 170);
    doc.setLineWidth(0.3);
    doc.line(marginL, y, pw - marginR, y);
    y += 6;

    // Reset text color
    doc.setTextColor(0, 0, 0);

    // If multi-column, record the starting Y for columns
    var colStartY = y;

    // ── Notes ──
    ordered.forEach(function (note) {
      // Estimate how much space this note needs
      var labelHeight = 5;
      var sourceHeight = 4;
      var bulletLines = 0;
      var wrappedBullets = [];

      doc.setFontSize(9);
      (note.bullets || []).forEach(function (bullet) {
        var lines = doc.splitTextToSize('\u2013  ' + bullet, colW - 2);
        wrappedBullets.push(lines);
        bulletLines += lines.length;
      });

      var totalHeight = labelHeight + sourceHeight + bulletLines * 3.8 + 6;

      // Check if we need to move to next column or page
      if (y + Math.min(totalHeight, 30) > ph - marginB) {
        if (cols > 1 && curCol < cols - 1) {
          nextCol();
        } else {
          newPage();
          colStartY = y;
        }
      }

      var x = colX[curCol];

      // Page label
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(0, 0, 0);
      doc.text((note.at || '').toUpperCase(), x, y);
      y += 4;

      // File source
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      doc.setTextColor(130, 130, 130);
      var srcLines = doc.splitTextToSize(note.file || '', colW - 2);
      doc.text(srcLines, x, y);
      y += srcLines.length * 3 + 2;

      // Bullets
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(0, 0, 0);

      wrappedBullets.forEach(function (lines) {
        // Check space for at least 1 line
        if (y + 4 > ph - marginB) {
          if (cols > 1 && curCol < cols - 1) {
            nextCol();
          } else {
            newPage();
            colStartY = y;
          }
          x = colX[curCol];
        }

        lines.forEach(function (line) {
          if (y + 4 > ph - marginB) {
            if (cols > 1 && curCol < cols - 1) {
              nextCol();
            } else {
              newPage();
              colStartY = y;
            }
            x = colX[curCol];
          }
          doc.text(line, x + 1, y);
          y += 3.8;
        });
        y += 0.5;
      });

      y += 4; // space between notes
    });

    doc.save(name);
    return { name: name };
  }

  root.GR = root.GR || {};
  root.GR.exporter = { save: save, downloadPDF: downloadPDF };
})(typeof window !== 'undefined' ? window : globalThis);
