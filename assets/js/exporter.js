/**
 * Produces the two save formats: a self-contained HTML file and a real PDF
 * download (no print dialog).
 *
 * save(paper)               → triggers download of grimm-<title>.html
 * downloadPDF(paper, cols)  → renders notes to a PDF and downloads it directly
 */
(function (root) {
  'use strict';

  function slug(title) {
    return String(title || 'notes')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 48) || 'notes';
  }

  function downloadBlob(blob, name) {
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = name;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 2000);
  }

  /** Grabs the full text of the first stylesheet on the page. */
  async function getCSS() {
    var links = Array.prototype.slice.call(document.querySelectorAll('link[rel="stylesheet"]'));
    for (var i = 0; i < links.length; i += 1) {
      try {
        var res = await fetch(links[i].href);
        if (res.ok) {
          var css = await res.text();
          if (css.indexOf('@page') < 0) {
            css = '@page { margin: 0; }\n' + css;
          }
          return css;
        }
      } catch (err) { /* skip */ }
    }
    return '@page { margin: 0; }';
  }

  /** Grabs the source text of a <script src="..."> tag. */
  async function getScript(src) {
    try {
      var res = await fetch(src);
      return res.ok ? await res.text() : '';
    } catch (err) {
      return '';
    }
  }

  function esc(str) {
    return String(str == null ? '' : str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  /**
   * Builds a self-contained HTML document that boots the notes viewer with
   * the paper JSON embedded, using no external resources.
   */
  async function buildHtml(paper) {
    var css = await getCSS();
    var scripts = await Promise.all([
      getScript('assets/js/notes.js'),
    ]);

    var safeJson = JSON.stringify(paper).replace(/<\/script/gi, '<\\/script');

    var doc = [
      '<!doctype html>',
      '<html lang="en" data-theme="dark">',
      '<head>',
      '<meta charset="utf-8" />',
      '<meta name="viewport" content="width=device-width, initial-scale=1" />',
      '<title>' + esc(paper.title || 'Grimm Notes') + '</title>',
      '<style>' + css + '</style>',
      '<script>',
      'try { var _t = localStorage.getItem("gr-theme");',
      'document.documentElement.setAttribute("data-theme", _t === "light" ? "light" : "dark"); } catch(e){}',
      '<\/script>',
      '</head>',
      '<body class="offline">',
      '<header class="masthead">',
      '  <div class="masthead-in">',
      '    <span class="wordmark">Grimm</span>',
      '    <span class="masthead-right">',
      '      <span class="masthead-meta">' + esc(paper.title || '') + ' \u00b7 ' + esc(paper.made || '') + '</span>',
      '      <button class="theme no-print" id="theme" type="button">&#9789;</button>',
      '    </span>',
      '  </div>',
      '</header>',
      '<main class="shell" id="notes-root"></main>',
      '<footer class="footer shell no-print">',
      '  <p>Generated by Grimm. For study use only.</p>',
      '</footer>',
      '',
      '<script>',
      scripts[0],
      '<\/script>',
      '<script>',
      '(function(){',
      '  var paper = ' + safeJson + ';',
      '  var root = document.getElementById("notes-root");',
      '  GR.notes.mount(root, paper, { mode: paper.mode || "chronological" });',
      '',
      '  var THEME_KEY = "gr-theme";',
      '  var themeBtn = document.getElementById("theme");',
      '  function themeNow(){ return document.documentElement.getAttribute("data-theme") === "light" ? "light" : "dark"; }',
      '  function paintTheme(){ themeBtn.textContent = themeNow() === "dark" ? "\\u263d" : "\\u2600"; }',
      '  themeBtn.addEventListener("click", function(){',
      '    var next = themeNow() === "dark" ? "light" : "dark";',
      '    document.documentElement.setAttribute("data-theme", next);',
      '    try{ localStorage.setItem(THEME_KEY, next); }catch(e){}',
      '    paintTheme();',
      '  });',
      '  paintTheme();',
      '})();',
      '<\/script>',
      '</body>',
      '</html>',
    ].join('\n');

    return doc;
  }

  /** Saves the offline HTML file. */
  async function save(paper) {
    var html = await buildHtml(paper);
    var name = 'grimm-' + slug(paper.title) + '.html';
    var blob = new Blob([html], { type: 'text/html; charset=utf-8' });
    downloadBlob(blob, name);
    return { name: name, size: blob.size };
  }

  /* ── PDF generation ─────────────────────────────────────────────────────── */

  var html2pdfLib = null;

  /** Load html2pdf.js from CDN on first use. */
  function loadHtml2Pdf() {
    if (html2pdfLib) return Promise.resolve(html2pdfLib);
    return new Promise(function (resolve, reject) {
      var script = document.createElement('script');
      script.src = 'https://cdn.jsdelivr.net/npm/html2pdf.js@0.10.2/dist/html2pdf.bundle.min.js';
      script.onload = function () { html2pdfLib = root.html2pdf; resolve(html2pdfLib); };
      script.onerror = function () { reject(new Error('Could not load the PDF library. Check your internet connection.')); };
      document.head.appendChild(script);
    });
  }

  /**
   * Builds a temporary DOM element with the notes rendered in a clean,
   * white, flat layout suitable for PDF generation.
   */
  function buildPdfContent(paper, columns) {
    var cols = columns || 1;
    var notes = paper.notes || [];
    var ordered = notes;

    // Respect stored order for randomised mode
    if (paper.mode === 'randomised' && paper.order && paper.order.length === notes.length) {
      ordered = paper.order.map(function (i) { return notes[i]; });
    }

    var wrap = document.createElement('div');
    wrap.style.cssText = 'background:#fff; color:#000; font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Arial,sans-serif; font-size:11pt; line-height:1.45; padding:0;';

    // Title
    var h = document.createElement('h1');
    h.textContent = paper.title || 'Notes';
    h.style.cssText = 'font-size:22pt; font-weight:700; letter-spacing:-0.02em; margin:0 0 4px;';
    wrap.appendChild(h);

    // Meta line
    var meta = document.createElement('p');
    meta.textContent = ordered.length + (ordered.length === 1 ? ' slide' : ' slides') +
      ' \u00b7 ' + (paper.mode === 'randomised' ? 'Randomised order' : 'Chronological order') +
      ' \u00b7 ' + (paper.made || '');
    meta.style.cssText = 'color:#555; font-size:9pt; margin:0 0 10px; padding-bottom:8px; border-bottom:1px solid #aaa;';
    wrap.appendChild(meta);

    // Notes grid
    var grid = document.createElement('div');
    grid.style.cssText = 'column-count:' + cols + '; column-gap:2em;';

    ordered.forEach(function (note) {
      var card = document.createElement('div');
      card.style.cssText = 'break-inside:avoid; margin-bottom:14px; page-break-inside:avoid;';

      var label = document.createElement('div');
      label.style.cssText = 'font-size:10pt; font-weight:700; text-transform:uppercase; letter-spacing:0.03em; color:#000; margin-bottom:1px;';
      label.textContent = note.at || '';
      card.appendChild(label);

      var source = document.createElement('div');
      source.style.cssText = 'font-size:8pt; color:#777; margin-bottom:6px;';
      source.textContent = note.file || '';
      card.appendChild(source);

      (note.bullets || []).forEach(function (bullet) {
        var line = document.createElement('p');
        line.style.cssText = 'margin:0 0 4px; font-size:10pt; line-height:1.45; color:#000;';
        line.textContent = '\u2013\u00a0\u00a0' + bullet;
        card.appendChild(line);
      });

      grid.appendChild(card);
    });

    wrap.appendChild(grid);
    return wrap;
  }

  /**
   * Generates a real PDF file and downloads it. No print dialog.
   * columns: 1 | 2 | 3
   */
  async function downloadPDF(paper, columns) {
    var cols = [1, 2, 3].indexOf(Number(columns)) >= 0 ? Number(columns) : 1;
    var name = 'grimm-' + slug(paper.title) + '.pdf';

    var h2p = await loadHtml2Pdf();
    var content = buildPdfContent(paper, cols);

    // Temporarily add to DOM for rendering (hidden)
    content.style.position = 'fixed';
    content.style.left = '-9999px';
    content.style.top = '0';
    content.style.width = '190mm'; // A4 minus margins
    document.body.appendChild(content);

    try {
      await h2p(content, {
        margin:       [12, 12, 12, 12],
        filename:     name,
        image:        { type: 'jpeg', quality: 0.98 },
        html2canvas:  { scale: 2, useCORS: true, backgroundColor: '#ffffff' },
        jsPDF:        { unit: 'mm', format: 'a4', orientation: 'portrait' },
        pagebreak:    { mode: ['avoid-all', 'css'] },
      }).save();
    } finally {
      document.body.removeChild(content);
    }

    return { name: name };
  }

  root.GR = root.GR || {};
  root.GR.exporter = { save: save, downloadPDF: downloadPDF };
})(typeof window !== 'undefined' ? window : globalThis);
